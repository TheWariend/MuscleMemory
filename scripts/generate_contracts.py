"""Generate TypeScript input contracts and an OpenAPI snapshot from Python models."""

import json
from pathlib import Path

from musclememory.api import create_app
from musclememory.core import (
    CreateRunInput,
    EvaluateInput,
    ExecutionEvent,
    InspectInput,
    LearnInput,
    MemoryLookupInput,
    ObserveInput,
    ProcedureDefinition,
    RecallInput,
    SessionUsageInput,
)

ROOT = Path(__file__).resolve().parents[1]
MODELS = [
    CreateRunInput,
    ObserveInput,
    LearnInput,
    RecallInput,
    EvaluateInput,
    InspectInput,
    ExecutionEvent,
    ProcedureDefinition,
    SessionUsageInput,
    MemoryLookupInput,
]


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" not in schema:
            if schema.get("patternProperties"):
                values = set(ts_type(value) for value in schema["patternProperties"].values())
                return f"Record<string, {' | '.join(sorted(values))}>"
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        fields = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};"
            for key, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    schemas = {}
    for model in MODELS:
        schema = model.model_json_schema()
        schemas.update(schema.pop("$defs", {}))
        schemas[model.__name__] = schema
    code = "// Generated by scripts/generate_contracts.py. Do not edit.\n"
    code += (
        "\n\n".join(
            f"export type {name} = {ts_type(schema)};" for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    target = ROOT / "packages/sdk-typescript/src/contracts.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(code)
    (ROOT / "docs/openapi.json").write_text(json.dumps(create_app().openapi(), indent=2) + "\n")


if __name__ == "__main__":
    generate()
